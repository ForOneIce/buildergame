const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  fs.mkdirSync('private/qa',{recursive:true});
  const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_BIN||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
  await page.locator('[data-enter]').first().click();
  await page.locator('#scene[data-town-ready="true"]').waitFor({timeout:60000});
  await page.waitForTimeout(1500);
  await page.screenshot({path:'private/qa/town-overview.png'});
  console.log('overview',await page.locator('#scene').evaluate(e=>({...e.dataset})));
  await page.locator('#timeline').fill('0'); await page.locator('#timeline').dispatchEvent('input');
  await page.locator('#scene[data-town-ready="true"]').waitFor({timeout:60000});
  await page.waitForTimeout(1000);await page.screenshot({path:'private/qa/town-early.png'});
  await page.locator('#timeline').fill('2'); await page.locator('#timeline').dispatchEvent('input');
  await page.locator('#scene[data-town-ready="true"]').waitFor({timeout:60000});
  await page.locator('[data-project="sample-3"]').click();await page.keyboard.press('Escape');
  await page.waitForTimeout(2500);
  await page.locator('#scene[data-town-ready="true"]').waitFor({timeout:60000});
  await page.screenshot({path:'private/qa/town-close.png'});
  console.log('close',await page.locator('#scene').evaluate(e=>({...e.dataset})));
  assert.ok(Number(await page.locator('#scene').getAttribute('data-high-detail'))>0);
  await page.setViewportSize({width:390,height:844});await page.locator('#show-projects').click();await page.locator('#reset').click();await page.waitForTimeout(1500);
  await page.screenshot({path:'private/qa/town-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);await browser.close();console.log('Town UI checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
